def normalize(code: str) -> str:
    return code if code in LANGUAGES else "zh-cn"


_current = normalize(Config.reload_config()[1])
_listeners: list[Callable[[str], None]] = []


def get_language() -> str:
    return _current


def tr(key: str, language: str | None = None, **values) -> str:
    code = normalize(language or _current)
    template = TEXT.get(code, TEXT["zh-cn"]).get(key, TEXT["zh-cn"].get(key, key))
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def subscribe(callback: Callable[[str], None]) -> Callable[[str], None]:
    if callback not in _listeners:
        _listeners.append(callback)
    return callback


def unsubscribe(callback: Callable[[str], None]) -> None:
    if callback in _listeners:
        _listeners.remove(callback)


def set_language(code: str, persist: bool = True) -> None:
    global _current
    code = normalize(code)
    _current = code
    if persist:
        settings_path = Config.get_writable_path("Settings.json")
        settings = {}
        if os.path.exists(settings_path):
            try:
                with open(settings_path, "r", encoding="utf-8") as handle:
                    settings = json.load(handle)
            except (OSError, json.JSONDecodeError):
                settings = {}
        settings["Language"] = code
        with open(settings_path, "w", encoding="utf-8") as handle:
            json.dump(settings, handle, indent=4, ensure_ascii=False)
    for callback in list(_listeners):
        try:
            callback(code)
        except Exception:
            # A closing Toplevel may disappear between a click and notification.
            pass
